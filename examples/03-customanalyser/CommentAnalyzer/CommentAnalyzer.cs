using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace CommentAnalyzer
{
    [DiagnosticAnalyzer(LanguageNames.CSharp)]
    public sealed class CommentAnalyzer : DiagnosticAnalyzer
    {
        const int MaxSingleLineChars = 10;
        const int MaxBlockChars = 15;

        public static readonly DiagnosticDescriptor NonEssentialCommentRule = new DiagnosticDescriptor(
            "COMMENT01",
            "Non-essential comment",
            "{0}",
            "Maintainability",
            DiagnosticSeverity.Warning,
            isEnabledByDefault: true,
            description: "Reports comments that are not file headers, documentation comments, or too short to be useful.");

        public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics =>
            ImmutableArray.Create(NonEssentialCommentRule);

        public override void Initialize(AnalysisContext context)
        {
            context.EnableConcurrentExecution();
            context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.None);
            context.RegisterSyntaxTreeAction(AnalyzeSyntaxTree);
        }

        static void AnalyzeSyntaxTree(SyntaxTreeAnalysisContext context)
        {
            var root = context.Tree.GetRoot(context.CancellationToken);

            foreach (var trivia in root.DescendantTrivia())
            {
                if ( IsDocComment(trivia)
                    || !IsReportable(trivia))
                    continue;

                context.ReportDiagnostic(Diagnostic.Create(
                    NonEssentialCommentRule,
                    trivia.GetLocation(),
                    "Comments are a code smell. They are either redundant or a signal that code should be written better."));
            }
        }

        static bool IsDocComment(SyntaxTrivia trivia) =>
            trivia.Kind() is SyntaxKind.SingleLineDocumentationCommentTrivia
                or SyntaxKind.MultiLineDocumentationCommentTrivia;

        static bool IsReportable(SyntaxTrivia trivia)
        {
            var text = trivia.ToString().Trim();
            if (text.Contains("ReSharper disable") || text.Contains("<auto-generated"))
                return false;

            return trivia.Kind() switch
            {
                SyntaxKind.SingleLineCommentTrivia => text.Length >= MaxSingleLineChars,
                SyntaxKind.MultiLineCommentTrivia => text.Length >= MaxBlockChars,
                SyntaxKind.SingleLineDocumentationCommentTrivia => text.Length >= MaxBlockChars,
                SyntaxKind.MultiLineDocumentationCommentTrivia => text.Length >= MaxBlockChars,
                _ => false
            };
        }
    }
}
